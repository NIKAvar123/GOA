function printArray(arr) {

    // გადავდივართ ყველა ელემენტზე
    for(let i = 0; i < arr.length; i++) {
        console.log(arr[i]);
    }
}

// ყველა ელემენტზე ერთხელ გადადის

// Big O = O(n)




// =====================================================
// 10) ყველაზე დიდი რიცხვის პოვნა
// =====================================================

function findMax(arr) {

    // თავიდან მაქსიმუმი არის პირველი ელემენტი
    let max = arr[0];

    // ვამოწმებთ დანარჩენ ელემენტებს
    for(let i = 1; i < arr.length; i++) {

        // თუ ახალი ელემენტი უფრო დიდია
        if(arr[i] > max) {

            // ვანახლებთ მაქსიმუმს
            max = arr[i];
        }
    }

    // ვაბრუნებთ ყველაზე დიდ რიცხვს
    return max;
}

// საჭიროა ყველა ელემენტის შემოწმება

// Big O = O(n)