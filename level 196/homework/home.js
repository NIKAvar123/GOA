
// 1) რა არის Encoding და რატომ არ ითვლება უსაფრთხოების მეთოდად?

// Encoding არის მონაცემების ერთი ფორმატიდან მეორე ფორმატში გადაყვანის პროცესი, რათა ინფორმაცია სწორად გადაიცეს ან დამუშავდეს სხვადასხვა სისტემებში.

// მაგალითებია:
// - ASCII
// - Unicode
// - Base64

// Encoding-ის მთავარი მიზანია მონაცემთა თავსებადობის უზრუნველყოფა და არა ინფორმაციის დაცვა.

// Encoding არ ითვლება უსაფრთხოების მეთოდად, რადგან encoded მონაცემის აღდგენა ძალიან მარტივია და ამისთვის საიდუმლო გასაღები არ არის საჭირო. ნებისმიერ ადამიანს, ვინც იცის გამოყენებული encoding-ის ტიპი, შეუძლია მონაცემის საწყის ფორმაში დაბრუნება.

// --------------------------------------------------

// 2) რა არის Encryption და რისთვის გამოიყენება?

// Encryption არის ინფორმაციის დაშიფვრის პროცესი, რომლის დროსაც ჩვეულებრივი ტექსტი (Plaintext) გარდაიქმნება გაუგებარ ფორმად (Ciphertext).

// Encryption-ის დროს გამოიყენება სპეციალური გასაღები (Key), რომლის გარეშე ინფორმაციის წაკითხვა შეუძლებელია.

// Encryption გამოიყენება:
// - ინტერნეტში მონაცემების უსაფრთხო გადაცემისთვის
// - ონლაინ ბანკინგში
// - ელფოსტაში
// - ფაილების დასაცავად
// - VPN-ებში

// Encryption-ის მთავარი მიზანია ინფორმაციის კონფიდენციალურობის დაცვა.

// --------------------------------------------------

// 3) რა არის Hashing და რატომ გამოიყენება პაროლების შესანახად?

// Hashing არის მონაცემის გარდაქმნა ფიქსირებული სიგრძის უნიკალურ მნიშვნელობად, რომელსაც ჰეში (Hash) ეწოდება.

// Hashing არის ერთმხრივი პროცესი (One-Way Function), რაც ნიშნავს, რომ მიღებული ჰეშიდან საწყისი მონაცემის აღდგენა პრაქტიკულად შეუძლებელია.

// პაროლების შესანახად Hashing გამოიყენება იმიტომ, რომ:
// - პაროლები ღია ტექსტად არ ინახება
// - მონაცემთა ბაზის გაჟონვის შემთხვევაშიც პაროლები პირდაპირ არ ჩანს
// - ავტორიზაციის დროს შეყვანილი პაროლი ჰეშირდება და შედეგი ინახულ ჰეშს ედარება

// პოპულარული Hashing ალგორითმებია:
// - SHA-256
// - bcrypt
// - scrypt
// - Argon2

// --------------------------------------------------

// 4) Encoding, Encryption და Hashing-ის შედარება

// Encoding
// - მიზანი: მონაცემის ფორმატის შეცვლა
// - უსაფრთხოება: არა
// - გასაღები: არ გამოიყენება
// - შებრუნება: შესაძლებელია

// Encryption
// - მიზანი: ინფორმაციის დაცვა
// - უსაფრთხოება: დიახ
// - გასაღები: გამოიყენება
// - შებრუნება: შესაძლებელია მხოლოდ სწორი გასაღებით

// Hashing
// - მიზანი: უნიკალური ანაბეჭდის შექმნა
// - უსაფრთხოება: დიახ
// - გასაღები: არ გამოიყენება
// - შებრუნება: შეუძლებელია

// --------------------------------------------------

// 5) თითოეულის მთავარი მიზანი

// Encoding:
// მონაცემების ისეთი ფორმით წარმოდგენა, რომ სხვადასხვა სისტემებმა სწორად წაიკითხონ და გადასცენ.

// Encryption:
// ინფორმაციის დაცვა არასანქცირებული წვდომისგან და კონფიდენციალურობის უზრუნველყოფა.

// Hashing:
// მონაცემის უნიკალური ანაბეჭდის შექმნა, მონაცემთა მთლიანობის შემოწმება და პაროლების უსაფრთხოდ შენახვა.

